package security

import (
	"bytes"
	"testing"
)

func TestMachineCrypto_RoundTrip(t *testing.T) {
	secret := "test-machine-id-12345-uid-1000"
	plaintext := []byte("super-secret-master-key-32-bytes!!")

	ciphertext, err := machineProtectWithSecret(plaintext, secret)
	if err != nil {
		t.Fatalf("machineProtectWithSecret failed: %v", err)
	}

	if bytes.Equal(ciphertext, plaintext) {
		t.Fatal("ciphertext must NOT match plaintext (must be encrypted)")
	}
	if !bytes.HasPrefix(ciphertext, []byte(magicHeader)) {
		t.Fatalf("ciphertext must start with magic header %q", magicHeader)
	}

	decrypted, err := machineUnprotectWithSecret(ciphertext, secret)
	if err != nil {
		t.Fatalf("machineUnprotectWithSecret failed: %v", err)
	}

	if !bytes.Equal(decrypted, plaintext) {
		t.Fatalf("decrypted %q != plaintext %q", decrypted, plaintext)
	}
}

func TestMachineCrypto_TamperingDetected(t *testing.T) {
	secret := "test-machine-id-12345-uid-1000"
	plaintext := []byte("sensitive-payload-to-tamper-with")

	ciphertext, err := machineProtectWithSecret(plaintext, secret)
	if err != nil {
		t.Fatalf("machineProtectWithSecret failed: %v", err)
	}

	// Tamper with the last byte (auth tag)
	tampered := make([]byte, len(ciphertext))
	copy(tampered, ciphertext)
	tampered[len(tampered)-1] ^= 0xFF

	_, err = machineUnprotectWithSecret(tampered, secret)
	if err == nil {
		t.Fatal("expected decryption error on tampered ciphertext, got nil")
	}
}

func TestMachineCrypto_WrongMachineSecretFails(t *testing.T) {
	secretA := "machine-host-A-uid-1000"
	secretB := "machine-host-B-uid-1000"
	plaintext := []byte("data-for-machine-A-only")

	ciphertext, err := machineProtectWithSecret(plaintext, secretA)
	if err != nil {
		t.Fatalf("machineProtectWithSecret failed: %v", err)
	}

	_, err = machineUnprotectWithSecret(ciphertext, secretB)
	if err == nil {
		t.Fatal("expected decryption error when decrypting with different machine secret, got nil")
	}
}

func TestMachineCrypto_LegacyPlaintextFallback(t *testing.T) {
	secret := "test-machine-id"
	// 32-byte raw plaintext key as generated by older Linux builds without magic header
	legacyKey := []byte("01234567890123456789012345678901")

	decrypted, err := machineUnprotectWithSecret(legacyKey, secret)
	if err != nil {
		t.Fatalf("expected legacy key to be accepted without error, got: %v", err)
	}
	if !bytes.Equal(decrypted, legacyKey) {
		t.Fatalf("expected decrypted legacy key %q to match %q", decrypted, legacyKey)
	}
}

func TestMachineCrypto_EmptyData(t *testing.T) {
	secret := "test-machine-id"

	res, err := machineProtectWithSecret(nil, secret)
	if err != nil || res != nil {
		t.Fatalf("expected (nil, nil) for nil plaintext, got (%v, %v)", res, err)
	}

	res, err = machineUnprotectWithSecret(nil, secret)
	if err != nil || res != nil {
		t.Fatalf("expected (nil, nil) for nil ciphertext, got (%v, %v)", res, err)
	}
}

