export type IconName = keyof typeof PATHS;

/**
 * Разметка иконки.
 *
 * aria-hidden без исключений: ни одна иконка здесь не остаётся единственным
 * носителем смысла — рядом всегда либо текст, либо подпись для скринридера у
 * элемента-хозяина. Иконка, которая ничего не сообщает вспомогательным
 * технологиям, обязана и молчать, а не читаться вслух как «изображение».
 *
 * Возвращается строка, а не узел: половина мест собирается через innerHTML из
 * готовых констант (так уже сделано с иконкой воспроизведения в истории), а
 * там, где карточки строятся через DOM API ради безопасности, разметка иконки
 * — фиксированная константа и никаких пользовательских данных в себе не несёт.
 */
export function iconSvg(name: IconName, size = 16, strokeWidth = 2): string {
  return (
    `<svg class="icon" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" ` +
    `stroke="currentColor" stroke-width="${strokeWidth}" stroke-linecap="round" ` +
    `stroke-linejoin="round" aria-hidden="true" focusable="false">${PATHS[name]}</svg>`
  );
}
